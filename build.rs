use std::env;
use std::path::PathBuf;
use std::process::Command;

fn cuda_arch_flag() -> String {
    // Colab T4 = 7.5, A100 = 8.0, etc. Override with CUDA_COMPUTE_CAP=7.5
    let cap = env::var("CUDA_COMPUTE_CAP").unwrap_or_else(|_| "7.5".into());
    let arch = if cap.contains('.') {
        format!("sm_{}", cap.replace('.', ""))
    } else {
        format!("sm_{cap}")
    };
    format!("-arch={arch}")
}

fn compile_cu(cu: &PathBuf, ptx: &PathBuf, include_dir: &PathBuf) -> bool {
    let mut cmd = Command::new("nvcc");
    cmd.arg("-ptx")
        .arg(cu)
        .arg("-o")
        .arg(ptx)
        .arg("-O3")
        .arg(format!("-I{}", include_dir.display()))
        .arg("--std=c++17")
        .arg(cuda_arch_flag());
    match cmd.status() {
        Ok(s) if s.success() => true,
        Ok(s) => {
            println!(
                "cargo:warning=nvcc failed for {} (status {s}) — continuing without custom PTX",
                cu.display()
            );
            false
        }
        Err(e) => {
            println!("cargo:warning=nvcc not found ({e}) — Candle CUDA still works without custom PTX");
            false
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=src/kernels/cuda/sentinel.cu");
    println!("cargo:rerun-if-changed=src/kernels/cuda/fp8_kernels.cu");
    println!("cargo:rerun-if-changed=src/kernels/cuda/fp8.cuh");
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CUDA_COMPUTE_CAP");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_CUDA");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let cuda_dir = PathBuf::from("src/kernels/cuda");
    let cuda_feature = env::var("CARGO_FEATURE_CUDA").is_ok();

    let mut sentinel_ptx = String::new();
    let mut fp8_ptx_blob = String::new();
    let mut built = false;

    if cuda_feature {
        let main_cu = cuda_dir.join("sentinel.cu");
        let main_ptx = out_dir.join("sentinel_kernels.ptx");
        if main_cu.exists() && compile_cu(&main_cu, &main_ptx, &cuda_dir) {
            if let Ok(s) = std::fs::read_to_string(&main_ptx) {
                sentinel_ptx = s;
                built = true;
            }
        }

        let fp8_cu = cuda_dir.join("fp8_kernels.cu");
        let fp8_ptx = out_dir.join("fp8_kernels.ptx");
        if fp8_cu.exists() {
            let mut cmd = Command::new("nvcc");
            cmd.arg("-ptx")
                .arg(&fp8_cu)
                .arg("-o")
                .arg(&fp8_ptx)
                .arg("-O3")
                .arg(format!("-I{}", cuda_dir.display()))
                .arg("--std=c++17")
                .arg(cuda_arch_flag());
            match cmd.status() {
                Ok(s) if s.success() => {
                    if let Ok(s) = std::fs::read_to_string(&fp8_ptx) {
                        fp8_ptx_blob = s;
                        built = true;
                        println!("cargo:warning=FP8 CUDA kernels built");
                    }
                }
                Ok(s) => println!(
                    "cargo:warning=FP8 nvcc failed (status {s}) — FP8 kernels disabled"
                ),
                Err(e) => println!("cargo:warning=nvcc missing for FP8 ({e})"),
            }
        }

        if built {
            println!("cargo:rustc-cfg=sentinel_cuda_kernels");
        } else {
            println!(
                "cargo:warning=Custom PTX not built; training/inference still use Candle CUDA ops"
            );
        }
    }

    let rs = out_dir.join("sentinel_ptx.rs");
    if built {
        let sentinel_built = !sentinel_ptx.is_empty();
        let fp8_built = !fp8_ptx_blob.is_empty();
        let esc = |s: &str| s.replace('\\', "\\\\").replace('"', "\\\"");
        std::fs::write(
            &rs,
            format!(
                "// @generated by build.rs\n\
pub const SENTINEL_PTX: &str = \"{}\";\n\
pub const SENTINEL_FP8_PTX: &str = \"{}\";\n\
pub const SENTINEL_KERNELS_BUILT: bool = {};\n\
pub const SENTINEL_FP8_BUILT: bool = {};\n",
                esc(&sentinel_ptx),
                esc(&fp8_ptx_blob),
                sentinel_built,
                fp8_built
            ),
        )
        .unwrap();
    } else {
        std::fs::write(
            &rs,
            "// @generated\n\
pub const SENTINEL_PTX: &str = \"\";\n\
pub const SENTINEL_FP8_PTX: &str = \"\";\n\
pub const SENTINEL_KERNELS_BUILT: bool = false;\n\
pub const SENTINEL_FP8_BUILT: bool = false;\n",
        )
        .unwrap();
    }
}
